function handleFiles(files) {
  if (!files || files.length === 0) return;

  uploadedImagesArray = []; // Reset stored images for new uploads
  const previewBox = document.getElementById('previewBox');
  const preview = document.getElementById('preview');
  const processBtn = document.getElementById('processBtn');

  let loadedCount = 0;
  const fileList = Array.from(files);

  fileList.forEach((file, index) => {
    if (!file.type.startsWith('image/')) return;

    const reader = new FileReader();
    reader.onload = function(e) {
      const base64Data = e.target.result.split(',')[1];
      uploadedImagesArray.push({
        mimeType: file.type,
        data: base64Data
      });

      // Show the first image as a preview
      if (index === 0) {
        preview.src = e.target.result;
        previewBox.style.display = 'block';
      }

      loadedCount++;
      if (loadedCount === fileList.length) {
        processBtn.disabled = false;
        processBtn.className = "w-full bg-cyan-600 text-white font-black py-4 rounded-2xl hover:bg-cyan-800 transition shadow-lg";
      }
    };
    reader.readAsDataURL(file);
  });
}

