async function saveWordDocument() {
  const el = document.getElementById('outputBox');
  if (!el) return;

  // Clone element to convert elements without affecting screen view
  const containerClone = el.cloneNode(true);

  // 1. Convert <svg> tags directly into MS Word-compatible <img> elements with base64 Data URIs
  const svgElements = Array.from(containerClone.querySelectorAll('svg'));
  svgElements.forEach((svg) => {
    try {
      // Extract exact bounding dimensions or default to standard size
      const rect = svg.getBoundingClientRect();
      const width = svg.getAttribute('width') || rect.width || 400;
      const height = svg.getAttribute('height') || rect.height || 200;

      // Ensure explicit width/height attributes are set on the SVG
      svg.setAttribute('width', width);
      svg.setAttribute('height', height);

      // Serialize the SVG XML tree to clean string
      const xml = new XMLSerializer().serializeToString(svg);
      const svgBase64 = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(xml)));

      // Build explicit <img> replacement for MS Word
      const img = document.createElement('img');
      img.src = svgBase64;
      img.width = width;
      img.height = height;
      img.style.cssText = `width:${width}px; height:${height}px; display:block; margin:10px auto;`;

      svg.parentNode.replaceChild(img, svg);
    } catch (err) {
      console.error("SVG Conversion error:", err);
    }
  });

  // 2. Ensure all existing <img> tags have explicit dimension & layout inline styles for MS Word
  const existingImages = Array.from(containerClone.querySelectorAll('img'));
  existingImages.forEach((img) => {
    img.style.maxWidth = '100%';
    img.style.height = 'auto';
    img.style.display = 'block';
    img.style.margin = '10px auto';
  });

  let content = containerClone.innerHTML;

  // Word specific styles (MSO office schema compatible)
  const docStyles = `
  <style>
    @page { size: A4; margin: 15mm; }
    body { font-family: 'Calibri', 'Times New Roman', serif; line-height: 1.6; color: #111; }
    .exam-header { text-align: center; border-bottom: 2px solid #000; margin-bottom: 20px; padding-bottom: 10px; font-weight: bold; }
    .section-head { font-weight: bold; text-decoration: underline; margin-top: 25px; display: block; text-transform: uppercase; }
    table { width: 100%; border-collapse: collapse; margin: 15px 0; border: 1px solid black; }
    th, td { border: 1px solid black; padding: 8px; vertical-align: top; }
    img { display: block; margin: 10px auto; max-width: 100%; }
  </style>
  `;

  // Wrap inside full HTML document structure for Word parser
  const convertedHtml = `
  <html xmlns:v="urn:schemas-microsoft-com:vml" xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word" xmlns="http://www.w3.org/TR/REC-html40">
  <head>
    <meta charset="utf-8">
    <!--[if gte mso 9]>
    <xml>
      <w:WordDocument>
        <w:View>Print</w:View>
        <w:Zoom>100</w:Zoom>
        <w:DoNotOptimizeForCustomX选m/>
      </w:WordDocument>
    </xml>
    <![endif]-->
    <title>Academic Document</title>
    ${docStyles}
  </head>
  <body>
    <div class="container">${content}</div>
  </body>
  </html>
  `;

  // Dynamic Name Resolution
  const rawTopic = document.getElementById('examTopic')?.value || 
                   document.getElementById('noteTopic')?.value || '';
  const cleanTopic = rawTopic.trim().replace(/[^a-zA-Z0-9_\-]/g, '_');
  const timeStamp = new Date().toISOString().slice(0, 10);
  const dynamicFileName = cleanTopic ? `${cleanTopic}_${timeStamp}.doc` : `Wonderz_Academic_${timeStamp}.doc`;

  // Execute Bridge Call directly
  if (window.AndroidPrint && typeof window.AndroidPrint.saveWordToDevice === "function") {
    if (window.AndroidPrint.saveWordToDevice.length >= 2) {
      window.AndroidPrint.saveWordToDevice(convertedHtml, dynamicFileName);
    } else {
      window.AndroidPrint.saveWordToDevice(convertedHtml);
    }
  }
}


