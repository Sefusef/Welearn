function startLocalAnalysisLoop() {
  const hiddenCanvas = document.createElement('canvas');
  const hiddenCtx = hiddenCanvas.getContext('2d');

  intervalId = setInterval(() => {
    if (!stream || !stream.active) return;
    if (isCooldownActive) return;

    const currentWidth = video.videoWidth || video.clientWidth || 600;
    const currentHeight = video.videoHeight || video.clientHeight || 450;

    hiddenCanvas.width = currentWidth;
    hiddenCanvas.height = currentHeight;
    hiddenCtx.drawImage(video, 0, 0, currentWidth, currentHeight);

    const frameDataUrl = hiddenCanvas.toDataURL('image/jpeg', 0.5);
    if (frameDataUrl && frameDataUrl.length > 5000) {
      saveCapturedFrameLocally(frameDataUrl);
    }
  }, 1200);
}

