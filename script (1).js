async function preprocessImages(files) {
const imgs = await Promise.all(Array.from(files).map(file =>
new Promise(res => {
const reader = new FileReader();
reader.onload = e => {
const img = new Image();
img.onload = () => res(img);
img.src = e.target.result;
};
reader.readAsDataURL(file);
})
));

const canvas = document.createElement('canvas');
const ctx = canvas.getContext('2d');
const targetWidth = 1200;
let totalHeight = 0;
imgs.forEach(img => totalHeight += targetWidth * (img.height / img.width));

canvas.width = targetWidth;
canvas.height = totalHeight;
ctx.filter = 'contrast(110%) brightness(105%)';

let currentY = 0;
imgs.forEach(img => {
const h = targetWidth * (img.height / img.width);
ctx.drawImage(img, 0, currentY, targetWidth, h);
currentY += h;
});

return canvas.toDataURL('image/jpeg', 0.9);
}

