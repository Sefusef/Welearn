function processData() {
  let roster = currentClassStudents.map(stu => {
    let marks = {};
    let total = 0;
    let count = 0;
    let contributions = [];

    currentClassMarks.forEach(m => {
      const studentPtr = m.get("student");
      if (studentPtr && studentPtr.id === stu.id && m.get("subject")) {
        const subName = m.get("subject").toUpperCase().trim();
        const val = Number(m.get("score")) || 0;
        marks[subName] = val;
      }
    });

    currentClassContributions.forEach(c => {
      const studentPtr = c.get("student");
      if (studentPtr && studentPtr.id === stu.id) {
        contributions.push({
          name: c.get("feeName") || "Unknown Contribution",
          total: c.get("totalAmount") || 0,
          paid: c.get("paidAmount") || 0,
          remain: (c.get("totalAmount") || 0) - (c.get("paidAmount") || 0)
        });
      }
    });

    availableSubjects.forEach(sub => {
      if(marks[sub] !== undefined) {
        total += marks[sub];
        count++;
      }
    });

    return {
      id: stu.id,
      name: stu.get("studentName"),
      sex: stu.get("gender") || "M",
      marks,
      contributions,
      total,
      avg: count > 0 ? (total / count) : 0
    };
  });
  roster.sort((a, b) => b.total - a.total);
  roster.forEach((s, i) => s.rank = i + 1);
  return roster;
}

