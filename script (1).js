async function saveAllScannedMarks(data, examId, cls) {
showLoading("Saving Records", "Synchronizing academic scores with database...");
const user = Parse.User.current();
const school = user.get("schoolName");
const Student = Parse.Object.extend("Students");
const Marks = Parse.Object.extend("Marks");

try {
  const sQuery = new Parse.Query(Student);
  sQuery.equalTo("assignedClass", cls);
  sQuery.equalTo("schoolName", school);
  let dbStudents = await sQuery.find();

  let saveBatch = [];
  let newStudentsToCreate = [];

  for (const entry of data) {
  let studentObj = dbStudents.find(s =>
  s.get("studentName").toUpperCase().includes(entry.name.toUpperCase()) ||
  entry.name.toUpperCase().includes(s.get("studentName").toUpperCase())
  );

  if (!studentObj) {
  const newStudent = new Student();
  newStudent.set("studentName", entry.name.toUpperCase().trim());
  newStudent.set("assignedClass", cls);
  newStudent.set("schoolName", school);
  newStudentsToCreate.push(newStudent);
  }
  }

  if (newStudentsToCreate.length > 0) {
  const savedNewStudents = await Parse.Object.saveAll(newStudentsToCreate);
  dbStudents = dbStudents.concat(savedNewStudents);
  }

  let discoveredSubjects = new Set();

  data.forEach(entry => {
  const studentObj = dbStudents.find(s =>
  s.get("studentName").toUpperCase().includes(entry.name.toUpperCase()) ||
  entry.name.toUpperCase().includes(s.get("studentName").toUpperCase())
  );

  if (studentObj) {
  for (let subjectName in entry.marks) {
  const score = entry.marks[subjectName];
  if (score !== null && score !== "") {
  const normalizedSubject = subjectName.toUpperCase().trim();
  discoveredSubjects.add(normalizedSubject);

  const m = new Marks();
  m.set("student", studentObj);
  m.set("exam", { __type: "Pointer", className: "Exams", objectId: examId });
  m.set("subject", normalizedSubject);
  m.set("score", Number(score));
  m.set("schoolName", school);
  saveBatch.push(m);
  }
  }
  }
  });

  if (saveBatch.length > 0) {
  await Parse.Object.saveAll(saveBatch);
  hideLoading();
  alert(`Successfully saved ${saveBatch.length} individual marks across parsed metrics!`);

  const selectElement = document.getElementById('mark-subject-select');
  if (selectElement) {
  discoveredSubjects.forEach(sub => {
  let optionExists = Array.from(selectElement.options).some(opt => opt.value === sub);
  if (!optionExists) {
  const newOpt = document.createElement('option');
  newOpt.value = sub;
  newOpt.innerText = sub;
  selectElement.appendChild(newOpt);
  }
  });

  if (discoveredSubjects.size > 0) {
  selectElement.value = Array.from(discoveredSubjects)[0];
  }
  }
  await loadMarkSheet();
  } else {
  hideLoading();
  alert("No valid marks were found to save.");
  }
} catch(e) {
  hideLoading();
  alert("Error saving marks: " + e.message);
}
}

