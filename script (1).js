function updateSubjectData() {
    const subj = document.getElementById('in-subject').value;
    const data = subjectData[subj];
    if (!data) return;

    const fillSelect = (id, list) => {
        const el = document.getElementById(id);
        if (el) el.innerHTML = list.map(item => `<option value="${item}">${item}</option>`).join('');
    };

    fillSelect('in-mcomp', data.mcomp);
    fillSelect('in-scomp', data.scomp);
    fillSelect('in-res', data.res);
    fillSelect('in-ref', data.ref);
    
    if (document.getElementById('in-mact')) {
        document.getElementById('in-mact').value = data.mact;
    }
    if (document.getElementById('in-res-final')) {
        document.getElementById('in-res-final').value = "";
    }
    saveSettings();
}

function autoFillLesson(subject, start, end, className) {
    const subInput = document.getElementById('in-subject');

    if (subInput && subject) {
        const incoming = subject.trim().toUpperCase();
        let matchFound = "";

        for (let key in subjectData) {
            if (key === incoming || incoming.includes(key) || key.includes(incoming)) {
                matchFound = key;
                break;
            }
        }

        if (matchFound) {
            subInput.value = matchFound;
            updateSubjectData(); 
        }
    }

    const formatForInput = (timeStr) => {
        if (!timeStr) return "";
        const parts = timeStr.split(':');
        if (parts.length < 2) return timeStr;
        const hh = parts[0].padStart(2, '0');
        const mm = parts[1].padStart(2, '0');
        return `${hh}:${mm}`;
    };

    if (document.getElementById('in-time')) {
        document.getElementById('in-time').value = formatForInput(start);
    }
    if (document.getElementById('in-end-time')) {
        document.getElementById('in-end-time').value = formatForInput(end);
    }
    if (document.getElementById('in-class')) {
        document.getElementById('in-class').value = className;
    }

    loadSettings();
}

