function calculateTotalMinutes(start, end) {
    if (!start || !end || typeof start !== 'string') return 40;

    const sParts = start.split(':');
    const eParts = end.split(':');

    if (sParts.length < 2 || eParts.length < 2) return 40;

    const h1 = parseInt(sParts[0], 10);
    const m1 = parseInt(sParts[1], 10);
    const h2 = parseInt(eParts[0], 10);
    const m2 = parseInt(eParts[1], 10);

    if (isNaN(h1) || isNaN(m1) || isNaN(h2) || isNaN(m2)) return 40;

    const totalStart = (h1 * 60) + m1;
    const totalEnd = (h2 * 60) + m2;
    let diff = totalEnd - totalStart;

    return (diff > 0) ? diff : 40;
}

