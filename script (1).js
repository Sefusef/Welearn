// Master network delivery processor incorporating remote config logic directly
async function callGeminiAPI(contents, systemInstruction = "", responseSchema = null, responseMimeType = null) {
  let apiKey = "";
  let modelName = "gemini-3.5-flash-lite"; // default fallback

  try {
    const AppConfig = await Parse.Object.extend("AppConfig");
    const query = new Parse.Query(AppConfig);
    query.descending("createdAt");
    const configObject = await query.first();

    if (configObject) {
      apiKey = configObject.get("geminiApiKey");
      modelName = configObject.get("geminiModel") || "gemini-3.5-flash-lite";
    } else {
      console.warn("No remote config found in Back4App. Using fallback.");
    }
  } catch (error) {
    console.error("Failed to load remote configuration from Back4App:", error);
  }

  const endpointUrl = `https://generativelanguage.googleapis.com/v1beta/models/${modelName}:generateContent?key=${apiKey}`;
  
  const payload = { contents: contents };
  
  if (systemInstruction) {
    payload.systemInstruction = { parts: [{ text: systemInstruction }] };
  }
  
  if (responseSchema || responseMimeType) {
    payload.generationConfig = {};
    if (responseMimeType) payload.generationConfig.responseMimeType = responseMimeType;
    if (responseSchema) payload.generationConfig.responseSchema = responseSchema;
    payload.generationConfig.temperature = 0.1;
  }

  const response = await fetch(endpointUrl, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    const errData = await response.json();
    throw new Error(errData.error?.message || "Failed to communicate with API");
  }

  const data = await response.json();
  return data.candidates[0].content.parts[0].text;
}

