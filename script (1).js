function getGrade(score) {
    if (score === '-') return '-';
    if (score >= 41) return 'A';
    if (score >= 31) return 'B';
    if (score >= 21) return 'C';
    if (score >= 11) return 'D';
    return 'E';
}

function getLocalEvaluationData(scoreAvg, rawTeacherName, rawHeadName) {
    const overallGrade = getGrade(scoreAvg);
    let classComment = "";
    let headComment = "";
    
    if (overallGrade === 'A' || overallGrade === 'B') {
        classComment = "Excellent performance, keep it up.";
        headComment = "Outstanding results this term.";
    } else if (overallGrade === 'C') {
        classComment = "Good effort, can improve.";
        headComment = "Satisfactory progress made here.";
    } else {
        classComment = "Needs work and focus.";
        headComment = "More academic effort required.";
    }
    
    const formatSig = (fullName) => {
        if (!fullName) return "...";
        const tokenized = fullName.trim().split(/\s+/);
        if (tokenized.length === 1) return tokenized[0];
        const initial = tokenized[0].charAt(0).toUpperCase();
        const surName = tokenized[tokenized.length - 1];
        const formattedSurName = surName.charAt(0).toUpperCase() + surName.slice(1).toLowerCase();
        return `${initial}.${formattedSurName}`;
    };

    return {
        classTeacherComment: classComment,
        headTeacherComment: headComment,
        classTeacherSignature: formatSig(rawTeacherName),
        headTeacherSignature: formatSig(rawHeadName)
    };
}

