async function downloadZipFromGitHub() {
  const statusDiv = document.getElementById('archiveStatus');
  const btn = document.getElementById('generateGuideBtn');
  if(!statusDiv) return;
  statusDiv.className = "text-amber-500 font-bold text-sm";
  statusDiv.innerText = "Downloading analytical bundle context from source...";

  try {
    const response = await fetch(GITHUB_ZIP_URL);
    if (!response.ok) throw new Error(`HTTP ${response.status}: Failed to grab context stream.`);

    const blobData = await response.blob();
    const zip = await JSZip.loadAsync(blobData);
    let combinedContent = [];
    let fileCount = 0;

    for (let relativePath in zip.files) {
      const zipEntry = zip.files[relativePath];
      const lowerPath = relativePath.toLowerCase();
      const pathSegments = relativePath.split('/');
      const fileName = pathSegments[pathSegments.length - 1];

      if (!zipEntry.dir && lowerPath.endsWith('.json') && !lowerPath.includes('__macosx') && !fileName.startsWith('.')) {
        const textContent = await zipEntry.async("string");
        combinedContent.push(`--- START OF FILE: ${relativePath} ---\n${textContent}\n--- END OF FILE ---\n`);
        fileCount++;
      }
    }

    if (fileCount === 0) {
      statusDiv.className = "text-rose-600 font-bold text-sm";
      statusDiv.innerText = "Error: Invalid bundle content.";
      return;
    }

    extractedExamsText = combinedContent.join("\n");
    statusDiv.className = "text-emerald-600 font-bold text-sm";
    statusDiv.innerText = `Connected successfully! (${fileCount} units loaded)`;
    
    btn.disabled = false;
    btn.className = "w-full bg-rose-600 text-white font-black py-4 rounded-2xl hover:bg-rose-800 transition shadow-lg";
    btn.innerText = "Train & Generate Strategic Guide";
  } catch (err) {
    statusDiv.className = "text-rose-600 font-bold text-sm";
    statusDiv.innerText = `Network pipeline error: ${err.message}`;
  }
}

